"""Generate docs/architecture/CAPABILITY_MATRIX.md from the catalogs and the analyzer registry.

    python tools/capability_matrix.py            # print the matrix
    python tools/capability_matrix.py --write    # rewrite the committed document
    python tools/capability_matrix.py --check    # exit 1 when the document is stale

The document is generated, never edited by hand; tests/test_documentation.py fails when it
is out of date. Fixture counts come from the test suite: the test modules that name a file
of the language.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "docs" / "architecture" / "CAPABILITY_MATRIX.md"

try:
    import project_discovery  # noqa: F401
except ImportError:  # a checkout without an installed package
    sys.path.insert(0, str(ROOT / "src"))

from project_discovery.analyzers import builtin_analyzers  # noqa: E402
from project_discovery.analyzers.code.tree_sitter_syntax import GRAMMARS  # noqa: E402
from project_discovery.catalog.domains import analyzer_domain_catalog  # noqa: E402
from project_discovery.catalog.languages import (  # noqa: E402
    language_catalog,
    language_files,
    source_language_names,
)

_MODEL = {"ast": "syntax tree", "lexical": "structural lexer"}
_LEVEL = {
    "implemented": "semantic",
    "lexical_structure": "structure",
    "optional_parser": "optional parser",
    "inventory_only": "inventory",
}
_FILE_NAME = re.compile(r"""["']([\w][\w./+-]{0,200}+)["']""")


def fixture_index(tests: Path) -> dict[str, set[str]]:
    """Lower-case file names and extensions named in each test module, by module."""
    index: dict[str, set[str]] = {}
    for module in sorted(tests.rglob("test_*.py")):
        names: set[str] = set()
        for match in _FILE_NAME.finditer(module.read_text(encoding="utf-8", errors="replace")):
            value = match.group(1).lower().rsplit("/", 1)[-1]
            names.add(value)
            if "." in value:
                names.add("." + value.rsplit(".", 1)[1])
        index[module.relative_to(tests).as_posix()] = names
    return index


def _names(names: list[str]) -> str:
    quoted = [f"`{name}`" for name in names]
    return ", ".join(quoted[:-1]) + (" and " if len(quoted) > 1 else "") + (quoted[-1] if quoted else "")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(tests: Path = ROOT / "tests") -> str:
    analyzers = builtin_analyzers()
    files = language_files()
    index = fixture_index(tests) if tests.is_dir() else {}
    languages = language_catalog()
    domains = analyzer_domain_catalog()
    sources = set(source_language_names())
    # Analyzers that read every source language are named once, not on every source row.
    polyglot = sorted(analyzer.name for analyzer in analyzers if sources <= set(analyzer.languages))
    by_language: dict[str, list[str]] = {}
    by_domain: dict[str, list[str]] = {}
    for analyzer in analyzers:
        for language in analyzer.languages:
            by_language.setdefault(language, []).append(analyzer.name)
        for domain in analyzer.domains:
            by_domain.setdefault(domain, []).append(analyzer.name)

    levels = Counter(item["analysis_status"] for item in languages)
    statuses = Counter(item["status"] for item in domains)
    lines = [
        "# Capability Matrix",
        "",
        "<!-- Generated by `python tools/capability_matrix.py --write` from the language and domain",
        "     catalogs and the built-in analyzer registry. Do not edit by hand:",
        "     tests/test_documentation.py fails when this file is out of date. -->",
        "",
        f"PDT recognizes {len(languages)} languages and formats and runs {len(analyzers)} built-in analyzers "
        f"over {len(domains)} analyzer domains. Recognition, structure and semantics are separate levels, "
        "and a language is listed at the level its code paths actually reach.",
        "",
        "## Levels and their limits",
        "",
        "| Level | Languages | What it provides | Limits |",
        "|---|---|---|---|",
        f"| semantic | {levels['implemented']} | Syntax tree, qualified symbols, calls resolved through imports, receiver "
        "classes stated or inferred, inter-procedural taint | No run-time types (dependency injection, `getattr`) |",
        f"| structure | {levels['lexical_structure']} | Definitions, calls, imports and references from a linear-time "
        "structural lexer, refined by a Tree-sitter grammar where provisioned | No types, overloads, macro "
        "expansion or templates |",
        f"| optional parser | {levels['optional_parser']} | Syntax-tree metrics, declarations and imports when the "
        "Tree-sitter grammar is provisioned (`tree-sitter-language-pack`) | Nothing beyond recognition without "
        "the grammar; PDT never downloads one |",
        f"| inventory | {levels['inventory_only']} | Recognized and counted; read by the format-specific analyzers "
        "listed | No code model |",
        "",
        "Analyzers are listed for a language when they declare it. "
        + _names(polyglot)
        + " read every source language and are not repeated on source rows. Format analyzers that select "
        "files by name (manifests, lockfiles, configuration, CI and archives) appear in the domain table. "
        "Fixtures counts the test modules that name a file of the language.",
        "",
        "## Languages and formats",
        "",
        "| Language | Family | Level | Code model | Tree-sitter grammar (optional) | Analyzers | Fixtures |",
        "|---|---|---|---|---|---|---:|",
    ]
    for item in sorted(languages, key=lambda entry: entry["name"].lower()):
        name = item["name"]
        model = _MODEL.get(item["structural_model"] or "", "—")
        if item["model_grammar"]:
            model += f", refined by Tree-sitter `{item['model_grammar']}`"
        extensions, filenames = files.get(name, ((), ()))
        wanted = {value.lower() for value in (*extensions, *filenames)}
        fixtures = sum(1 for names in index.values() if names & wanted)
        shown = sorted(
            analyzer for analyzer in by_language.get(name, [])
            if name not in sources or analyzer not in polyglot
        )
        lines.append(
            f"| {_cell(name)} | {item['family']} | {_LEVEL[item['analysis_status']]} | {model} | "
            f"{GRAMMARS.get(name, '—')} | {', '.join(shown) or '—'} | {fixtures} |"
        )
    lines += [
        "",
        "## Analyzer domains",
        "",
        f"{statuses.get('implemented', 0)} implemented, {statuses.get('partial', 0)} partial and "
        f"{statuses.get('planned', 0)} planned. A domain is `implemented` when its scope is covered end to end, "
        "`partial` when an analyzer covers part of it.",
        "",
        "| Domain | Status | Analyzers | Scope |",
        "|---|---|---|---|",
    ]
    for item in sorted(domains, key=lambda entry: entry["id"]):
        lines.append(
            f"| {item['id']} | {item['status']} | {', '.join(sorted(by_domain.get(item['id'], []))) or '—'} | "
            f"{_cell(item['scope'])} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="rewrite the committed document")
    group.add_argument("--check", action="store_true", help="exit 1 when the document is stale")
    args = parser.parse_args()
    text = render()
    if args.write:
        DOCUMENT.write_bytes(text.encode("utf-8"))
        return 0
    if args.check:
        current = DOCUMENT.read_bytes().decode("utf-8") if DOCUMENT.exists() else ""
        if current != text:
            print(f"{DOCUMENT.relative_to(ROOT)} is stale: run python tools/capability_matrix.py --write")
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
