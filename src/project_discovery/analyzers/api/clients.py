"""Generated API clients: the code OpenAPI code generators write, and the operations it calls.

A source file is a generated client when its first 8 KiB hold a generator's mark: openapi-generator,
swagger-codegen, swagger-typescript-api, NSwag, Kiota, AutoRest, oapi-codegen, ogen, orval,
openapi-typescript, @hey-api/openapi-ts and openapi-typescript-codegen. The operations it calls are
read from its path literals (``"/pets/{petId}"``, template literals included), with the HTTP method
the generator writes next to them where it writes one. The code index matches them with the scan's
contracts and routes. Nothing is generated or called.
"""
from __future__ import annotations

import bisect
import itertools
import re
from pathlib import Path

from ...core.limits import AnalyzerLimits, over_limit
from ...core.source_utils import SourceBudgetExceeded, read_text_bounded
from ...intelligence import facts as code_facts
from ...models import FileRecord, Finding
from ..base import Analyzer
from .integration import normalize_route
from .rpc import _Lines

MAX_CLIENT_BYTES = 16 * 1024 * 1024
MAX_CLIENT_OPERATIONS = 2000
MAX_PATH_LITERALS = 20_000
MAX_METHOD_MARKS = 200_000
MAX_CLIENT_EVIDENCE = 100
_HEAD_BYTES = 8192

# (generator, mark in the file's first 8 KiB)
_GENERATORS = (
    ("openapi-generator", re.compile(r"(?i)auto[- ]generated by openapi[- ]generator|openapi-generator\.tech|"
                                     r"generated by openapi-generator")),
    ("swagger-codegen", re.compile(r"(?i)auto generated by the swagger code generator|swagger-codegen")),
    ("swagger-typescript-api", re.compile(r"(?i)generated via swagger-typescript-api")),
    ("NSwag", re.compile(r"Generated using the NSwag toolchain")),
    ("Kiota", re.compile(r"Microsoft\.Kiota\.Abstractions|@microsoft/kiota-abstractions|microsoft/kiota-abstractions-go|"
                         r"kiota_abstractions")),
    ("AutoRest", re.compile(r"Code generated by Microsoft \(R\) AutoRest Code Generator")),
    ("oapi-codegen", re.compile(r"Code generated by github\.com/(?:deepmap|oapi-codegen)/oapi-codegen")),
    ("ogen", re.compile(r"Code generated by ogen\b")),
    ("orval", re.compile(r"(?i)generated by orval")),
    ("openapi-typescript", re.compile(r"auto-generated by openapi-typescript\b")),
    ("@hey-api/openapi-ts", re.compile(r"auto-generated by @hey-api/openapi-ts")),
    ("openapi-typescript-codegen", re.compile(r"openapi-typescript-codegen")),
)
_EXTENSIONS = frozenset({".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts", ".java", ".kt", ".kts",
                         ".scala", ".cs", ".go", ".php", ".rb", ".swift", ".dart", ".rs"})
# Path literals: "/pets/{petId}", `/pets/${petId}`, '/store/order'; NSwag's operation path comments
# (written without the leading slash) and Kiota's URL templates.
_PATH_LITERALS = (
    re.compile(r"""["'`](?P<path>/[^"'`\s]{1,300})["'`]"""),
    re.compile(r"""\bOperation Path: "(?P<path>[^"\n]{1,300})\""""),
    re.compile(r"""["']\{\+baseurl\}(?P<path>/[^"'\s]{0,300})["']"""),
)
# The HTTP method a generator writes near a path: method: 'GET', HttpMethod.Get, http.MethodGet,
# Method.GET, "POST", axios.get(.
_METHOD_NEAR = re.compile(r"""(?i)\bmethod\s*+[:=]\s*+["'`]?(?P<a>get|post|put|patch|delete|head|options)\b|"""
                          r"""\b(?:http)?method[._]?(?P<b>get|post|put|patch|delete|head|options)\b|"""
                          r"""["'`](?P<c>GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)["'`]|"""
                          r"""\.(?P<d>get|post|put|patch|delete|head|options)\s*+(?:<[^<>()\n]{0,200}+>)?\(""")
_METHOD_BEFORE, _METHOD_AFTER = 400, 1500
_LETTER = re.compile(r"[A-Za-z]")
# RFC 6570 query and fragment expressions in URL templates: /pets{?limit,offset}.
_TEMPLATE_QUERY = re.compile(r"\{[?&#][^{}]{0,200}+\}")
_NOT_PATHS = re.compile(r"(?i)^/(?:\*|usr|etc|tmp|var|bin|dev|proc|home)(?:/|$)|\.(?:js|ts|json|css|html|png|svg)$")


def generator_of(head: str) -> str:
    """The OpenAPI code generator whose mark the head of a file holds, or ""."""
    for generator, mark in _GENERATORS:
        if mark.search(head):
            return generator
    return ""


def client_operations(text: str) -> list[tuple[str, str, int]]:
    """(method or "?", path template, line) of the operation paths a generated client calls; the
    method is the one written nearest the path."""
    lines = _Lines(text)
    # Every method mark once, by offset; each path takes the nearest within its window.
    marks = [(item.start(), next(value for value in item.groups() if value).upper())
             for item in itertools.islice(_METHOD_NEAR.finditer(text), MAX_METHOD_MARKS)]
    offsets = [offset for offset, _ in marks]
    found: dict[tuple[str, str], int] = {}
    examined = 0
    for pattern in _PATH_LITERALS:
        for match in pattern.finditer(text):
            examined += 1
            if examined > MAX_PATH_LITERALS:
                break
            raw = _TEMPLATE_QUERY.sub("", match.group("path"))
            if not _LETTER.search(raw) or _NOT_PATHS.search(raw):
                continue
            path = normalize_route(raw if raw.startswith("/") else "/" + raw)
            index = bisect.bisect_left(offsets, match.start())
            candidates = [(match.start() - offsets[index - 1], marks[index - 1][1])] if index and \
                match.start() - offsets[index - 1] <= _METHOD_BEFORE else []
            if index < len(marks) and offsets[index] - match.start() <= _METHOD_AFTER:
                candidates.append((offsets[index] - match.start(), marks[index][1]))
            key = (min(candidates)[1] if candidates else "?", path)
            if key not in found:
                if len(found) >= MAX_CLIENT_OPERATIONS:
                    break
                found[key] = lines.line(match.start())
    return sorted(((method, path, line) for (method, path), line in found.items()), key=lambda item: (item[2], item[1]))


class GeneratedClientAnalyzer(Analyzer):
    """Generated OpenAPI clients and the operations they call, statically."""

    name = "api-clients"
    limits = AnalyzerLimits(MAX_CLIENT_BYTES, "whole", {"head_bytes": _HEAD_BYTES, "operations": MAX_CLIENT_OPERATIONS},
                            outcome="no finding past the budget: the generator's mark is not read")
    domains = ("api_rest", "build_systems")
    languages = ("Python", "JavaScript", "TypeScript", "Java", "Kotlin", "Scala", "C#", "Go", "PHP", "Ruby", "Swift",
                 "Dart", "Rust")

    def supports(self, record: FileRecord) -> bool:
        return record.error is None and record.extension in _EXTENSIONS

    def analyze(self, path: Path, record: FileRecord) -> list[Finding]:
        if over_limit(record.size_bytes, MAX_CLIENT_BYTES):
            return []
        try:
            text = read_text_bounded(path, MAX_CLIENT_BYTES, errors="replace", expected_identity=record.analysis_identity)
        except (OSError, ValueError, SourceBudgetExceeded):
            return []
        generator = generator_of(text[:_HEAD_BYTES])
        if not generator:
            return []
        operations = client_operations(text)
        for method, route, line in operations:
            code_facts.emit_fact("api_client_operation", f"{method} {route}", generator=generator, line=line)
        code_facts.emit_fact("api_client", generator, operations=len(operations))
        return [Finding(
            "api", f"Generated API client: {record.path}",
            f"Written by {generator}: {len(operations)} operation path(s). Generated code is regenerated from its "
            "contract, not edited.",
            confidence="CONFIRMED", analyzer=self.name,
            evidence=[f"{record.path}:{line} {method} {route}" for method, route, line in operations[:MAX_CLIENT_EVIDENCE]]
            or [record.path],
        )]
