def _record(tmp_path: Path, relative: str, source: str) -> tuple[Path, FileRecord]:
    path = tmp_path / "source"
    path.write_text(source, encoding="utf-8")
    return path, FileRecord(relative, path.stat().st_size, Path(relative).suffix.lower(), "Source")


def _facts(facts, kind: str) -> list[tuple[str, dict]]:
    return [(name, json.loads(detail)) for fact_kind, name, detail in facts.facts if fact_kind == kind]


def test_generated_clients_by_generator_mark():
    assert generator_of(AXIOS) == "openapi-generator"
    assert generator_of("// Generated using the NSwag toolchain v14.0.3.0 (http://NSwag.org)") == "NSwag"
    assert generator_of("// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.1.0 DO NOT EDIT.") \
        == "oapi-codegen"
    assert generator_of("/**\n * Generated by orval v6.25.0\n */") == "orval"
    assert generator_of("// This file was auto-generated by openapi-typescript.") == "openapi-typescript"
    assert generator_of("using Microsoft.Kiota.Abstractions;") == "Kiota"
    # A hand-written client that calls the same paths is not generated.
    assert generator_of("// pets client\nexport const get = () => axios.get('/pets');\n") == ""


def test_generated_client_operations_with_their_methods():
    assert client_operations(AXIOS) == [("POST", "/pets", 11), ("GET", "/pets/{}", 23), ("GET", "/pets/{}/photos", 34)]
    python = ("class PetApi:\n    def _get(self, pet_id):\n        return self.api_client.param_serialize(\n"
              "            method='GET',\n            resource_path='/pet/{petId}',\n        )\n"
              "    def _delete(self, pet_id):\n        return self.api_client.param_serialize(\n"
              "            method='DELETE',\n            resource_path='/pet/{petId}',\n        )\n")
    assert [item[:2] for item in client_operations(python)] == [("GET", "/pet/{}"), ("DELETE", "/pet/{}")]
    nswag = ('request_.Method = new System.Net.Http.HttpMethod("GET");\n// Operation Path: "pet/{petId}"\n'
             'urlBuilder_.Append("pet/");\n')
    assert [item[:2] for item in client_operations(nswag)] == [("GET", "/pet/{}")]
    go = 'operationPath := fmt.Sprintf("/pets/%s", pathParam0)\nreq, err := http.NewRequest("GET", queryURL.String(), nil)\n'
    assert [item[:2] for item in client_operations(go)] == [("GET", "/pets/{}")]
    orval = "return axios.get(`/pets/${petId}`, options);\n" + "\n" * 60 + "return axios.post(`/pets`, body, options);\n"
    assert [item[:2] for item in client_operations(orval)] == [("GET", "/pets/{}"), ("POST", "/pets")]
    kiota = 'public PetsRequestBuilder(...) : base(requestAdapter, "{+baseurl}/pets{?limit}", pathParameters) {}\n'
    assert [item[1] for item in client_operations(kiota)] == ["/pets"]
    # File paths and content types are not operations.
    assert client_operations("const a = '/usr/local/bin'; const b = '/static/app.js'; const c = '/';\n") == []


def test_generated_client_findings_and_facts(tmp_path: Path):
    path, record = _record(tmp_path, "client/api.ts", AXIOS)
    analyzer = GeneratedClientAnalyzer()
    assert analyzer.supports(record)
    with collecting_facts() as facts:
        findings = analyzer.analyze(path, record)
    assert [finding.title for finding in findings] == ["Generated API client: client/api.ts"]
    assert findings[0].detail.startswith("Written by openapi-generator: 3 operation path(s).")
    assert "client/api.ts:23 GET /pets/{}" in findings[0].evidence
    assert [name for name, _ in _facts(facts, "api_client_operation")] == ["POST /pets", "GET /pets/{}", "GET /pets/{}/photos"]
    path, record = _record(tmp_path, "src/app.ts", "fetch('/pets');\n")
    assert analyzer.analyze(path, record) == []


def test_contracts_record_operations_with_their_base_path(tmp_path: Path):
    assert openapi_base(OPENAPI) == "/v1"
    assert openapi_base({"swagger": "2.0", "basePath": "/api/"}) == "/api"
    assert openapi_base({"openapi": "3.1.0", "servers": [{"url": "/internal"}]}) == "/internal"
    assert openapi_base({"openapi": "3.1.0", "servers": [{"url": "{scheme}://example.com"}]}) == ""
    path, record = _record(tmp_path, "api/openapi.json", json.dumps(OPENAPI))
    analyzer = APIContractAnalyzer()
    assert analyzer.supports(record)
    with collecting_facts() as facts:
        analyzer.analyze(path, record)
    assert _facts(facts, "openapi_operation") == [
        ("GET /pets", {"base": "/v1", "operation_id": "listPets"}), ("POST /pets", {"base": "/v1", "operation_id": "createPet"}),
        ("GET /pets/{petId}", {"base": "/v1", "operation_id": "showPetById"}),
        ("DELETE /pets/{petId}", {"base": "/v1", "operation_id": "deletePet"})]


def test_openapi_documents_with_other_names_are_read_by_content(tmp_path: Path):
    swagger = json.dumps({"swagger": "2.0", "info": {"title": "x", "version": "1"}, "basePath": "/api",
                          "paths": {"/orders": {"get": {"operationId": "listOrders"}}}})
    path, record = _record(tmp_path, "specs/orders.json", swagger)
    analyzer = ProtocolEndpointAnalyzer()
    with collecting_facts() as facts:
        findings = analyzer.analyze(path, record)
    assert [finding.title for finding in findings] == ["OpenAPI operations: specs/orders.json"]
    assert findings[0].evidence == ["GET /orders (listOrders)"]
    assert _facts(facts, "openapi_operation") == [("GET /orders", {"base": "/api", "operation_id": "listOrders"})]
    # A document with a name api-contracts reads is left to it.
    path, record = _record(tmp_path, "openapi.json", json.dumps(OPENAPI))
    assert analyzer.analyze(path, record) == []


def test_the_operation_reader_is_linear_on_adversarial_input():
    for text in ("'/a'" * 50_000, "'/a' method: 'GET' " * 20_000, "// Operation Path: \"a" * 30_000, "`/" * 50_000):
        started = time.perf_counter()
        client_operations(text)
        assert time.perf_counter() - started < 10


def test_the_code_index_cross_references_routes_contracts_and_clients(tmp_path: Path):
    project = tmp_path / "project"
    files = {
        "api/openapi.json": json.dumps(OPENAPI),
        "server/app.py": ('from flask import Flask\napp = Flask(__name__)\n\n\n@app.get("/v1/pets")\ndef list_pets():\n'
                          '    return []\n\n\n@app.post("/v1/pets")\ndef create_pet():\n    return {}\n\n\n'
                          '@app.get("/v1/pets/<int:pet_id>")\ndef show_pet(pet_id):\n    return {}\n\n\n'
                          '@app.get("/health")\ndef health():\n    return "ok"\n'),
        "client/api.ts": AXIOS,
        "web/main.js": "fetch('/v1/pets').then((response) => response.json());\n",
    }
    for name, text in files.items():
        path = project / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    output = tmp_path / "out"
    assert run_scan(project, output, {"json"}, 1, quiet=True) == 0
    report = json.loads((output / "discovery-report.json").read_text(encoding="utf-8"))
    value = report["metrics"]["code_index"]["contract_links"]
    assert (value["operations"], value["implemented"]) == (4, 3)
    links = {(item["method"], item["path"]): item for item in value["links"]}
    assert [(route["file"], route["line"]) for route in links[("GET", "/pets/{petId}")]["routes"]] == [("server/app.py", 16)]
    assert links[("GET", "/pets/{petId}")]["clients"] == ["client/api.ts"]
    assert links[("GET", "/pets")]["calls"] >= 1
    assert value["unimplemented"] == [{"method": "DELETE", "path": "/pets/{petId}", "operation_id": "deletePet",
                                       "file": "api/openapi.json"}]
    assert [(item["method"], item["path"]) for item in value["undeclared_routes"]] == [("GET", "/health")]
    client = value["clients"][0]
    assert (client["file"], client["generator"], client["operations"], client["matched"]) == ("client/api.ts",
                                                                                              "openapi-generator", 3, 2)
    assert client["unmatched"] == [{"method": "GET", "path": "/pets/{}/photos", "line": 34}]
    titles = {item["title"] for item in report["findings"] if item["analyzer"] == "code-index"}
    assert {"API contracts and code", "Contract operations no route serves", "Routes no contract declares",
            "Generated client operations no contract declares"} <= titles
